const MULTILANG_LOOKUP = new Map<string, { category: AudioCategory; key: string }>()
for (const [lang, categories] of Object.entries(MULTILANG_SENTENCES)) {
  for (const [cat, items] of Object.entries(categories) as [AudioCategory, Array<[string, string]>][]) {
    for (const [key, text] of items) {
      MULTILANG_LOOKUP.set(`${lang}:${normalize(text)}`, { category: cat, key })
    }
  }
}

export function findMultilangAudioFile(answer: string, lang: MultilangLang): string | null {
  const match = MULTILANG_LOOKUP.get(`${lang}:${normalize(answer)}`)
  if (!match) return null
  const p = path.join(AUDIO_DIR, lang, 'default', match.category, `${match.key}.mp3`)
  try {
    fs.accessSync(p, fs.constants.R_OK)
    return p
  } catch {
    return null
  }
}

// businessType string → audio category
export function resolveCategory(businessType: string): AudioCategory {
  const t = businessType.toLowerCase()
  if (t.includes('restoran') || t.includes('kafe') || t.includes('bar') || t.includes('yemek')) return 'restoran'
  if (t.includes('güzellik') || t.includes('guzellik') || t.includes('spa') || t.includes('masaj') || t.includes('estetik')) return 'guzellik'
  if (t.includes('sağlık') || t.includes('saglik') || t.includes('klinik') || t.includes('diş') || t.includes('dis') || t.includes('psiko') || t.includes('terapi')) return 'saglik'
  if (t.includes('kuaför') || t.includes('kuafor') || t.includes('berber') || t.includes('saç') || t.includes('sac')) return 'kuafor'
  if (t.includes('pilates') || t.includes('reformer')) return 'pilates'
  return 'universal'
}

